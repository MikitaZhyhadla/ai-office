"use client"
import { useAppStore } from "@/store/useAppStore"
import { qaTestCaseAgent } from "@/agents/qaTestCaseAgent"
import { qaTestCaseAgentFromString } from "@/agents/qaTestCaseAgent"
import type { TestCase } from "@/types"

interface TestCasePanelProps {
  ticketId:    string
  ticketTitle: string
}

const TYPE_STYLE: Record<TestCase['type'], { background: string; color: string; label: string }> = {
  positive: { background: '#EAF3DE', color: '#27500A', label: 'Positive' },
  negative: { background: '#FCEBEB', color: '#791F1F', label: 'Negative' },
  boundary: { background: '#FAEEDA', color: '#633806', label: 'Boundary' },
}

export function TestCasePanel({ ticketId, ticketTitle }: TestCasePanelProps) {
  const testCasesMap  = useAppStore(s => s.testCases)
  const setTestCases  = useAppStore(s => s.setTestCases)
  const setGenerating = useAppStore(s => s.setGeneratingTc)
  const generatingFor = useAppStore(s => s.generatingTcFor)
  const ticket        = useAppStore(s => s.tickets.find(t => t.id === ticketId))

  const cases        = testCasesMap[ticketId] ?? []
  const isGenerating = generatingFor.includes(ticketId)
  const canGenerate  = !!ticket

  async function handleGenerate() {
    if (!ticket || isGenerating) return
    setGenerating(ticketId, true)
    try {
      let newCases: TestCase[]
      if (ticket.ticketType === 'bug' && ticket.bugReport) {
        const requirementText = `
Bug: ${ticket.title}
Severity: ${ticket.bugReport.severity}
Affected Area: ${ticket.bugReport.affectedArea}
Steps to Reproduce: ${ticket.bugReport.stepsToReproduce?.join('; ')}
Expected: ${ticket.bugReport.expectedBehavior}
Actual: ${ticket.bugReport.actualBehavior}
        `.trim()
        newCases = await qaTestCaseAgentFromString(requirementText)
      } else {
        newCases = await qaTestCaseAgent(ticketId, ticketTitle, ticket.data, ticket.format)
      }
      setTestCases(ticketId, newCases)
    } catch (e) {
      console.error('Failed to generate test cases:', e)
    } finally {
      setGenerating(ticketId, false)
    }
  }

  async function handleDownload() {
    const res = await fetch('/api/export-tests', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ ticketId, ticketTitle, testCases: cases }),
    })
    const blob = await res.blob()
    const url  = URL.createObjectURL(blob)
    const a    = document.createElement('a')
    a.href     = url
    a.download = `test-cases-${ticketId}.xlsx`
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 14 }}>
        <span style={{ fontSize: 10, color: '#aaa', textTransform: 'uppercase', letterSpacing: '0.05em', fontWeight: 600 }}>
          Generated by QA Agent
        </span>
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
          {canGenerate && (
            <button
              onClick={handleGenerate}
              disabled={isGenerating}
              style={{
                background: isGenerating ? '#f0eff7' : '#534AB7',
                color: isGenerating ? '#9994D4' : '#fff',
                border: isGenerating ? '1px solid #d0cef0' : 'none',
                borderRadius: 6,
                padding: '6px 12px',
                fontSize: 11,
                cursor: isGenerating ? 'not-allowed' : 'pointer',
                fontWeight: 500,
                display: 'flex',
                alignItems: 'center',
                gap: 5,
                fontFamily: 'inherit',
              }}
            >
              {isGenerating ? (
                <>
                  <span style={{ display: 'inline-block', animation: 'spin 1s linear infinite' }}>⟳</span>
                  Generating...
                </>
              ) : (
                cases.length > 0 ? '⟳ Regenerate' : '⚡ Generate Test Cases'
              )}
            </button>
          )}
          {cases.length > 0 && (
            <button
              onClick={handleDownload}
              style={{
                background: '#0F6E56', color: '#E1F5EE', border: 'none',
                borderRadius: 6, padding: '6px 12px', fontSize: 11,
                cursor: 'pointer', fontWeight: 500,
              }}
            >
              ↓ Download XLSX
            </button>
          )}
        </div>
      </div>

      {cases.length === 0 && !isGenerating ? (
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center',
                      height: 120, color: '#aaa', fontSize: 13, textAlign: 'center' }}>
          {canGenerate
            ? 'No test cases yet — drag ticket to In Progress or click ⚡ Generate'
            : 'No test cases yet — drag ticket to In Progress to generate'}
        </div>
      ) : isGenerating && cases.length === 0 ? (
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center',
                      height: 120, color: '#0F6E56', fontSize: 13, gap: 8 }}>
          <span style={{ display: 'inline-block', animation: 'spin 1s linear infinite', fontSize: 16 }}>⟳</span>
          Generating test cases…
        </div>
      ) : (
        cases.map(tc => {
          const ts = TYPE_STYLE[tc.type]
          return (
            <div key={tc.id} style={{
              background: '#f8f8fc', border: '1px solid #e8e8f0',
              borderRadius: 8, padding: 12, marginBottom: 8,
            }}>
              <div style={{ display: 'flex', gap: 8, alignItems: 'center', marginBottom: 8 }}>
                <span style={{
                  fontSize: 10, fontWeight: 600, padding: '2px 8px',
                  borderRadius: 20, background: ts.background, color: ts.color,
                  flexShrink: 0,
                }}>
                  {ts.label}
                </span>
                <span style={{ fontSize: 12, fontWeight: 500, flex: 1 }}>{tc.title}</span>
              </div>

              <div>
                {tc.steps.map((step, i) => (
                  <div key={i} style={{
                    fontSize: 11, color: '#666', padding: '2px 0 2px 12px',
                    borderLeft: '2px solid #e0e0f0', margin: '3px 0',
                  }}>
                    {step}
                  </div>
                ))}
              </div>

              <div style={{ fontSize: 11, color: '#0F6E56', marginTop: 6, fontWeight: 500 }}>
                ✓ Expected: {tc.expectedResult}
              </div>
            </div>
          )
        })
      )}
      <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>
    </div>
  )
}
