"use client"
import { useState } from "react"
import { useSettingsStore } from "@/store/useSettingsStore"
import { runDevTechNotesAgent } from "@/agents/devTechNotesAgent"
import type { Ticket, TechNotes } from "@/types"

interface TechNotesPanelProps {
  ticket: Ticket
  onGenerated: (notes: TechNotes) => void
}

const sectionHeader: React.CSSProperties = {
  fontSize: 11,
  fontWeight: 700,
  color: "#534AB7",
  marginBottom: 6,
  marginTop: 14,
}

const pill: React.CSSProperties = {
  display: "inline-block",
  background: "#EEEDFE",
  color: "#534AB7",
  fontSize: 11,
  padding: "3px 10px",
  borderRadius: 20,
  margin: 2,
}

export function TechNotesPanel({ ticket, onGenerated }: TechNotesPanelProps) {
  const projectDescription = useSettingsStore(s => s.projectDescription)
  const [isLoading, setIsLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const hasNotes = Boolean(ticket.techNotes)

  async function handleGenerate() {
    setIsLoading(true)
    setError(null)
    try {
      const notes = await runDevTechNotesAgent(ticket, projectDescription)
      onGenerated(notes)
    } catch {
      setError('Failed to generate tech notes. Please try again.')
    } finally {
      setIsLoading(false)
    }
  }

  /* ── STATE B — Loading ── */
  if (isLoading) {
    return (
      <div style={{ display: "flex", flexDirection: "column", alignItems: "center", padding: "32px 0", gap: 16 }}>
        <div style={{
          width: 28,
          height: 28,
          border: "3px solid #e8e8f0",
          borderTop: "3px solid #534AB7",
          borderRadius: "50%",
          animation: "spin 0.8s linear infinite",
        }} />
        <div style={{ fontSize: 13, color: "#666" }}>Bob Dev is analysing the requirement...</div>
        <div style={{ width: "100%", display: "flex", flexDirection: "column", gap: 8, marginTop: 8 }}>
          {[60, 80, 45].map((w, i) => (
            <div key={i} style={{
              height: 12,
              width: `${w}%`,
              background: "#f0eff7",
              borderRadius: 6,
              animation: "pulse 1.5s ease-in-out infinite",
            }} />
          ))}
        </div>
      </div>
    )
  }

  /* ── STATE A — Empty ── */
  if (!hasNotes) {
    return (
      <div style={{ display: "flex", flexDirection: "column", alignItems: "center", textAlign: "center", padding: "32px 16px", gap: 10 }}>
        <div style={{ fontSize: 32 }}>🔧</div>
        <div style={{ fontSize: 14, fontWeight: 600, color: "#333" }}>Tech Notes</div>
        <div style={{ fontSize: 12, color: "#888", maxWidth: 320, lineHeight: 1.6 }}>
          On-demand technical implementation guide generated by the Dev agent for this ticket.
        </div>
        {error && (
          <div style={{ fontSize: 12, color: "#791F1F", marginTop: 4 }}>
            ⚠ {error}
          </div>
        )}
        <button
          onClick={handleGenerate}
          style={{
            marginTop: 8,
            background: "#534AB7",
            color: "#fff",
            border: "none",
            borderRadius: 8,
            padding: "9px 20px",
            fontSize: 12,
            fontWeight: 500,
            cursor: "pointer",
            fontFamily: "inherit",
          }}
        >
          ⚙ Generate Tech Notes
        </button>
        <div style={{ fontSize: 11, color: "#bbb", marginTop: 4 }}>
          Note: Only available for tickets in In Progress or later stages.
        </div>
      </div>
    )
  }

  /* ── STATE C — Notes rendered ── */
  const notes = ticket.techNotes!

  return (
    <div>
      {/* Header row */}
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: 12, paddingBottom: 12, borderBottom: "1px solid #f0f0f7" }}>
        <span style={{ fontSize: 10, fontWeight: 600, color: "#aaa", textTransform: "uppercase", letterSpacing: "0.6px" }}>
          Generated by Bob Dev
        </span>
        <button
          onClick={handleGenerate}
          style={{
            fontSize: 10,
            padding: "4px 10px",
            border: "1px solid #e8e8f0",
            borderRadius: 6,
            color: "#666",
            background: "#fff",
            cursor: "pointer",
            fontFamily: "inherit",
          }}
        >
          ↺ Regenerate
        </button>
      </div>

      {error && (
        <div style={{ fontSize: 12, color: "#791F1F", marginBottom: 10 }}>⚠ {error}</div>
      )}

      {/* Proposed Stack */}
      <div style={{ ...sectionHeader, marginTop: 0 }}>📦 Proposed Stack</div>
      <div>
        {notes.proposedStack.map((item, i) => (
          <span key={i} style={pill}>{item}</span>
        ))}
      </div>

      {/* Implementation Steps */}
      <div style={sectionHeader}>🔧 Implementation Steps</div>
      <ol style={{ margin: 0, paddingLeft: 16 }}>
        {notes.implementationSteps.map((step, i) => (
          <li key={i} style={{ fontSize: 12, color: "#444", lineHeight: 1.6 }}>{step}</li>
        ))}
      </ol>

      {/* Edge Cases */}
      <div style={sectionHeader}>⚠ Edge Cases</div>
      <ul style={{ margin: 0, paddingLeft: 16, listStyleType: "disc" }}>
        {notes.edgeCases.map((ec, i) => (
          <li key={i} style={{ fontSize: 12, color: "#444", lineHeight: 1.6 }}>{ec}</li>
        ))}
      </ul>

      {/* Patterns */}
      <div style={sectionHeader}>🏗 Patterns</div>
      <div>
        {notes.patterns.map((p, i) => (
          <span key={i} style={pill}>{p}</span>
        ))}
      </div>

      {/* Estimate Note */}
      <div style={sectionHeader}>📊 Estimate Note</div>
      <div style={{
        fontSize: 12,
        color: "#555",
        fontStyle: "italic",
        background: "#fafafa",
        borderRadius: 6,
        padding: "10px 12px",
        borderLeft: "3px solid #534AB7",
      }}>
        {notes.estimateNote}
      </div>
    </div>
  )
}
