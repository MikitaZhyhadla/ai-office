"use client"
import { useEffect, useState } from "react"
import type { RetroReport } from "@/types"

interface RetroModalProps {
  isOpen:            boolean
  report:            RetroReport | null
  sprintName:        string
  isLoading:         boolean
  avgCycleTimeDays:  number | null
  onClose:           () => void
  onExport:          () => void
  onStartNextSprint: () => void
}

function Skeleton({ width = "100%", height = 14 }: { width?: string | number; height?: number }) {
  return (
    <div style={{
      width, height, borderRadius: 6, background: "#ebebf5",
      animation: "skeleton-pulse 1.4s ease-in-out infinite",
    }} />
  )
}

function formatReportAsText(report: RetroReport): string {
  return `Sprint ${report.sprintName} Retrospective
================================
Velocity: ${report.velocity} SP | Tickets: ${report.completedTickets}/${report.totalTickets} | Revision rate: ${report.revisionRate}

What went well:
${report.highlights.map(h => `- ${h}`).join('\n')}

Blockers:
${report.blockers.map(b => `- ${b}`).join('\n')}

Suggestions:
${report.suggestions.map(s => `- ${s}`).join('\n')}

Agent Insights:
${report.agentInsights}`
}

export function RetroModal({
  isOpen,
  report,
  sprintName,
  isLoading,
  avgCycleTimeDays,
  onClose,
  onExport,
  onStartNextSprint,
}: RetroModalProps) {
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    if (!isOpen) return
    const handler = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose() }
    window.addEventListener('keydown', handler)
    return () => window.removeEventListener('keydown', handler)
  }, [isOpen, onClose])

  if (!isOpen) return null

  const today = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })

  function handleCopy() {
    if (!report) return
    navigator.clipboard.writeText(formatReportAsText(report)).then(() => {
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    })
  }

  return (
    <>
      <style>{`
        @keyframes skeleton-pulse {
          0%, 100% { opacity: 1; }
          50% { opacity: 0.4; }
        }
      `}</style>
      <div
        onClick={onClose}
        style={{
          position: "fixed", inset: 0, background: "rgba(0,0,0,0.6)",
          zIndex: 50, display: "flex", alignItems: "center", justifyContent: "center",
          overflowY: "auto", padding: "16px 0",
        }}
      >
        <div
          onClick={e => e.stopPropagation()}
          style={{
            background: "#fff", borderRadius: 12, maxWidth: 720, width: "95%",
            maxHeight: "90vh", overflowY: "auto", boxShadow: "0 20px 60px rgba(0,0,0,0.25)",
            display: "flex", flexDirection: "column",
          }}
        >
          {/* Header */}
          <div style={{
            display: "flex", alignItems: "flex-start", justifyContent: "space-between",
            padding: "20px 24px", borderBottom: "1px solid #f0f0f7",
          }}>
            <div>
              <div style={{ fontSize: 15, fontWeight: 700, color: "#1a1a2e", display: "flex", alignItems: "center", gap: 8 }}>
                <span>📊</span>
                <span>Sprint {sprintName} Retrospective</span>
              </div>
              <div style={{ fontSize: 11, color: "#999", marginTop: 4 }}>
                Generated by Alice BA · {today}
              </div>
            </div>
            <button
              onClick={onClose}
              style={{
                background: "none", border: "none", cursor: "pointer",
                fontSize: 18, color: "#aaa", padding: "2px 6px", lineHeight: 1,
                borderRadius: 4, fontFamily: "inherit",
              }}
            >
              ✕
            </button>
          </div>

          {/* Body */}
          <div style={{ padding: "20px 24px", flexGrow: 1 }}>
            {/* Stats row */}
            <div style={{ display: "flex", gap: 12, marginBottom: 20 }}>
              {/* Tickets closed */}
              <div style={{
                flex: 1, border: "1px solid #f0f0f7", borderRadius: 8,
                padding: 14, textAlign: "center",
              }}>
                {isLoading ? (
                  <><Skeleton width="60%" height={28} /><div style={{ marginTop: 6 }}><Skeleton width="80%" height={12} /></div></>
                ) : (
                  <>
                    <div style={{ fontSize: 24, fontWeight: 700, color: "#1a1a2e" }}>
                      {report?.completedTickets ?? 0}
                    </div>
                    <div style={{ fontSize: 11, color: "#888", marginTop: 4 }}>Tickets Closed</div>
                  </>
                )}
              </div>
              {/* Velocity */}
              <div style={{
                flex: 1, border: "1px solid #f0f0f7", borderRadius: 8,
                padding: 14, textAlign: "center",
              }}>
                {isLoading ? (
                  <><Skeleton width="60%" height={28} /><div style={{ marginTop: 6 }}><Skeleton width="80%" height={12} /></div></>
                ) : (
                  <>
                    <div style={{ fontSize: 24, fontWeight: 700, color: "#0F6E56" }}>
                      {report?.velocity ?? 0} SP
                    </div>
                    <div style={{ fontSize: 11, color: "#888", marginTop: 4 }}>Velocity</div>
                  </>
                )}
              </div>
              {/* Revision rate */}
              <div style={{
                flex: 1, border: "1px solid #f0f0f7", borderRadius: 8,
                padding: 14, textAlign: "center",
              }}>
                {isLoading ? (
                  <><Skeleton width="60%" height={28} /><div style={{ marginTop: 6 }}><Skeleton width="80%" height={12} /></div></>
                ) : (
                  <>
                    <div style={{ fontSize: 24, fontWeight: 700, color: "#854F0B" }}>
                      {report?.revisionRate ?? '—'}
                    </div>
                    <div style={{ fontSize: 11, color: "#888", marginTop: 4 }}>Revision Rate</div>
                  </>
                )}
              </div>
              {/* Avg cycle time */}
              <div style={{
                flex: 1, border: "1px solid #f0f0f7", borderRadius: 8,
                padding: 14, textAlign: "center",
              }}>
                {isLoading ? (
                  <><Skeleton width="60%" height={28} /><div style={{ marginTop: 6 }}><Skeleton width="80%" height={12} /></div></>
                ) : (
                  <>
                    <div style={{ fontSize: 24, fontWeight: 700, color: "#534AB7" }}>
                      {avgCycleTimeDays != null ? `${avgCycleTimeDays}d` : '—'}
                    </div>
                    <div style={{ fontSize: 11, color: "#888", marginTop: 4 }}>Avg Cycle Time</div>
                  </>
                )}
              </div>
            </div>

            {/* Sections grid */}
            <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 12 }}>
              {/* What went well */}
              <div style={{
                background: "#f0fff8", border: "1px solid #c8ecd4", borderRadius: 8, padding: 14,
              }}>
                <div style={{ fontSize: 12, fontWeight: 600, color: "#0F6E56", marginBottom: 10 }}>
                  ✅ What went well
                </div>
                {isLoading ? (
                  <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                    <Skeleton /><Skeleton width="85%" /><Skeleton width="90%" />
                  </div>
                ) : (
                  <ul style={{ margin: 0, padding: 0, listStyle: "none" }}>
                    {(report?.highlights ?? []).map((h, i) => (
                      <li key={i} style={{
                        fontSize: 12, color: "#444", padding: "4px 0",
                        borderBottom: "1px solid rgba(0,0,0,0.04)",
                      }}>
                        · {h}
                      </li>
                    ))}
                  </ul>
                )}
              </div>

              {/* Blockers */}
              <div style={{
                background: "#fff8f0", border: "1px solid #f0c890", borderRadius: 8, padding: 14,
              }}>
                <div style={{ fontSize: 12, fontWeight: 600, color: "#854F0B", marginBottom: 10 }}>
                  ⚠️ Blockers &amp; delays
                </div>
                {isLoading ? (
                  <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                    <Skeleton /><Skeleton width="80%" /><Skeleton width="70%" />
                  </div>
                ) : (
                  <ul style={{ margin: 0, padding: 0, listStyle: "none" }}>
                    {(report?.blockers ?? []).map((b, i) => (
                      <li key={i} style={{
                        fontSize: 12, color: "#444", padding: "4px 0",
                        borderBottom: "1px solid rgba(0,0,0,0.04)",
                      }}>
                        · {b}
                      </li>
                    ))}
                  </ul>
                )}
              </div>

              {/* Suggestions — full width */}
              <div style={{
                background: "#f8f0ff", border: "1px solid #d4c8f0", borderRadius: 8, padding: 14,
                gridColumn: "1 / -1",
              }}>
                <div style={{ fontSize: 12, fontWeight: 600, color: "#534AB7", marginBottom: 10 }}>
                  💡 Suggestions for next sprint
                </div>
                {isLoading ? (
                  <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                    <Skeleton /><Skeleton width="88%" /><Skeleton width="75%" />
                  </div>
                ) : (
                  <ul style={{ margin: 0, padding: 0, listStyle: "none" }}>
                    {(report?.suggestions ?? []).map((s, i) => (
                      <li key={i} style={{
                        fontSize: 12, color: "#444", padding: "4px 0",
                        borderBottom: "1px solid rgba(0,0,0,0.04)",
                      }}>
                        · {s}
                      </li>
                    ))}
                  </ul>
                )}
              </div>

              {/* Agent insights — full width */}
              <div style={{
                background: "#fafafa", border: "1px solid #e8e8f0", borderRadius: 8, padding: 14,
                gridColumn: "1 / -1",
              }}>
                <div style={{ fontSize: 12, fontWeight: 600, color: "#555", marginBottom: 10 }}>
                  🤖 Agent Insights
                </div>
                {isLoading ? (
                  <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                    <Skeleton /><Skeleton width="95%" /><Skeleton width="80%" />
                    <div style={{ marginTop: 4 }}>
                      <span style={{ fontSize: 12, color: "#888" }}>Alice BA is analysing the sprint...</span>
                    </div>
                  </div>
                ) : (
                  <p style={{ margin: 0, fontSize: 12, color: "#444", fontStyle: "italic", lineHeight: 1.6 }}>
                    {report?.agentInsights ?? ''}
                  </p>
                )}
              </div>
            </div>
          </div>

          {/* Footer */}
          <div style={{
            display: "flex", gap: 8, padding: "16px 24px",
            borderTop: "1px solid #f0f0f7", background: "#fafafa",
            alignItems: "center",
          }}>
            <button
              onClick={handleCopy}
              disabled={isLoading || !report}
              style={{
                background: "#fff", border: "1px solid #e0e0f0", borderRadius: 8,
                padding: "8px 14px", fontSize: 12, fontWeight: 500, cursor: "pointer",
                color: "#555", fontFamily: "inherit",
                opacity: isLoading ? 0.5 : 1,
              }}
            >
              {copied ? "✓ Copied!" : "⎘ Copy Report"}
            </button>
            <button
              onClick={onExport}
              disabled={isLoading || !report}
              style={{
                background: "#fff", border: "1px solid #e0e0f0", borderRadius: 8,
                padding: "8px 14px", fontSize: 12, fontWeight: 500, cursor: "pointer",
                color: "#555", fontFamily: "inherit",
                opacity: isLoading ? 0.5 : 1,
              }}
            >
              ↓ Export TXT
            </button>
            <button
              onClick={onStartNextSprint}
              style={{
                marginLeft: "auto", background: "#534AB7", color: "#fff",
                border: "none", borderRadius: 8, padding: "8px 16px",
                fontSize: 12, fontWeight: 500, cursor: "pointer", fontFamily: "inherit",
              }}
            >
              Start Next Sprint →
            </button>
          </div>
        </div>
      </div>
    </>
  )
}
